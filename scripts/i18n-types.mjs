import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/**
 * Generates the typed message contract from the English source catalog.
 *
 *   node scripts/i18n-types.mjs           write src/i18n/types.generated.ts
 *   node scripts/i18n-types.mjs --check   fail when the file has drifted
 */

export const TYPES_RELATIVE = "src/i18n/types.generated.ts";

export function renderTypes(catalog) {
  const keys = Object.keys(catalog);
  const lines = keys.map((key) => `  | ${JSON.stringify(key)}`).join("\n");
  return `/* This file is generated by scripts/i18n-types.mjs. Do not edit. */\n\nexport type MessageKey =\n${lines};\n\nexport type MessageCatalog = Record<MessageKey, string>;\n`;
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalogPath = resolve(root, "src/i18n/locales/en.json");
const typesPath = resolve(root, TYPES_RELATIVE);

async function main() {
  const catalog = JSON.parse(await readFile(catalogPath, "utf8"));
  const source = renderTypes(catalog);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = await readFile(typesPath, "utf8");
    } catch {
      current = "";
    }
    if (current !== source) {
      console.error(`${TYPES_RELATIVE} is out of date. Run node scripts/i18n-types.mjs.`);
      process.exitCode = 1;
      return;
    }
    console.log(`i18n types are current (${Object.keys(catalog).length} keys).`);
    return;
  }
  await writeFile(typesPath, source, "utf8");
  console.log(`Generated ${TYPES_RELATIVE} with ${Object.keys(catalog).length} keys.`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
